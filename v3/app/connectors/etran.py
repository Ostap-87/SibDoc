# -*- coding: utf-8 -*-
"""ЭТРАН (АС ЭТРАН ОАО «РЖД») — перевозочные документы по железной дороге (задел).

Прямой доступ (stage needs_access). Что нужно и у кого (Коннекторы/банк, docs/CONNECTORS.md):
  1) договор с ОАО «РЖД» на электронный обмен перевозочными документами в АС ЭТРАН —
     заключает грузоотправитель/грузополучатель (или его экспедитор) через ТЦФТО — центр
     фирменного транспортного обслуживания своей дороги;
  2) пользователь ЭТРАН (логин и пароль) с правами на нужные документы и код организации
     (плательщика) в ЭТРАН;
  3) квалифицированная электронная подпись организации (ГОСТ, КриптоПро CSP) — документы и
     запросы в ЭТРАН подписываются;
  4) для обмена «система — система» — доступ к веб-сервису ЭТРАН (адрес выдаёт РЖД по договору)
     и описание XML-сообщений («руководство программиста» веб-сервиса — выдаётся РЖД, в открытом
     доступе его нет). Пока его нет — формат запросов здесь не реализован.

Мост до доступа: export_dir — папка, куда логист сохраняет выгрузки из АРМ ЭТРАН (журнал накладных
«в Excel», CSV) или файлы от ж/д экспедитора. Файлы с номером накладной / вагона распознаются по
содержимому и идут в слот транспортных документов `transport` (пакет ВЭД; параметр slot — если нужен
другой слот).

  connectors:
    etran:
      type: etran
      enabled: false
      label: ЭТРАН (РЖД)
      export_dir: /data/incoming/etran   # выгрузки из АРМ ЭТРАН / от экспедитора
      slot: transport
      service_url: ""              # адрес веб-сервиса — выдаёт РЖД по договору
      login: ""
      password_env: SIBDOC_ETRAN_PASSWORD
      cert_thumbprint: ""          # отпечаток сертификата ЭЦП в хранилище КриптоПро
      org_code: ""                 # код организации/плательщика в ЭТРАН
"""
from __future__ import annotations

from .base import P
from .stub import EXPORT_PARAMS, StubConnector

ETRAN_MASKS = ["*.xlsx", "*.xls", "*.csv", "*.xml", "*.zip"]
TRANSPORT_SLOT = "transport"          # слот пакета ВЭД «Транспортный документ»


class EtranConnector(StubConnector):
    type = "etran"
    title = "ЭТРАН (РЖД): ж/д накладные и контейнеры"
    access_hint = ("договор с ОАО «РЖД» на доступ к веб-сервису АС ЭТРАН (через ТЦФТО): адрес "
                   "сервиса, логин и пароль пользователя ЭТРАН, сертификат ЭЦП организации "
                   "(ГОСТ, КриптоПро CSP) на сервере SibDoc; запрашивает отдел логистики или "
                   "ж/д экспедитор")
    protocol_note = ("формат XML-запросов ЭТРАН (накладные, состояние вагонов/контейнеров) и "
                     "порядок подписи ЭЦП уточнить у владельца системы (РЖД) по документации "
                     "веб-сервиса; пока можно указать export_dir — папку с выгрузками из АРМ ЭТРАН")
    need = ("договор с ОАО «РЖД» на электронный обмен в АС ЭТРАН, пользователь ЭТРАН и код организации, "
            "квалифицированная ЭЦП организации (ГОСТ, КриптоПро CSP) на сервере SibDoc, адрес веб-сервиса "
            "ЭТРАН и руководство программиста к нему")
    need_from = ("у ОАО «РЖД» через ТЦФТО своей дороги (договор, доступ, документация); ЭЦП — у удостоверяющего "
                 "центра; заявку подаёт отдел логистики или ж/д экспедитор")
    exports_hint = ("журнал накладных из АРМ ЭТРАН «в Excel» / CSV, файлы от ж/д экспедитора — слот "
                    "транспортных документов (параметр slot)")
    export_defaults = {"pattern": ETRAN_MASKS, "zip_masks": ETRAN_MASKS,
                       "slot_rules": [{"pattern": r"(?i)(накладн|etran|этран|ГУ-?29|ГУ-?27|вагон)",
                                       "slot": TRANSPORT_SLOT}]}
    content_slots = (TRANSPORT_SLOT,)
    params = [
        P("service_url", "Адрес веб-сервиса ЭТРАН (по договору с РЖД)", required=True,
          example="уточнить у РЖД"),
        P("login", "Пользователь ЭТРАН", required=True),
        P("password", "Пароль ЭТРАН", required=True, secret=True,
          example="password_env: SIBDOC_ETRAN_PASSWORD"),
        P("cert_thumbprint", "Отпечаток сертификата ЭЦП (КриптоПро)", required=True,
          example="3F2A...C9"),
        P("org_code", "Код организации/плательщика в ЭТРАН"),
        P("slot", "Слот для выгрузок (транспортные документы)", example=TRANSPORT_SLOT),
    ] + EXPORT_PARAMS

    @property
    def slot_aliases(self) -> dict:
        slot = str(self.opt("slot") or TRANSPORT_SLOT)
        return {TRANSPORT_SLOT: slot}

    def _folder(self):
        f = super()._folder()
        slot = str(self.opt("slot") or TRANSPORT_SLOT)
        if slot != TRANSPORT_SLOT and not self.cfg.get("slot_rules"):
            f.cfg["slot_rules"] = [dict(r, slot=slot) for r in self.export_defaults["slot_rules"]]
        return f
