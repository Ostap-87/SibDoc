def single_window_list() -> pd.DataFrame:
    """Список 报关单, выгруженный из «Единого окна» (货物申报 → 数据查询/统计 → 报关数据查询 → 导出)."""
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import make_demo
    rows = []
    for s in make_demo.SHIP:
        if not s.get("cn"):
            continue
        rows.append({"统一编号": f"I2026000{s['cn'][-6:]}", "海关编号": s["cn"], "进出口标志": "进口",
                     "申报日期": s["date_cn"], "境内收发货人": make_demo.CONSIGNEE_CN,
                     "境外发货人": "OOO PRIMER EXPORT (fictional)", "监管方式": "一般贸易", "运输方式": "铁路运输",
                     "合同协议号": s["contract"], "申报地海关": "满洲里海关", "报关单状态": "结关"})
    return pd.DataFrame(rows)


def main():
    out = {"bank": os.path.join(DEMO, "bank"), "bank_cn": os.path.join(DEMO, "bank_cn"),
           "1c": os.path.join(DEMO, "1c"), "sw": os.path.join(DEMO, "cn_single_window")}
    for d in out.values():
        os.makedirs(d, exist_ok=True)
    files = {os.path.join(out["bank"], "kl_to_1c_demo.txt"): one_c(),
             os.path.join(out["bank"], "camt053_demo.xml"): camt053(),
             os.path.join(out["bank"], "mt940_demo.sta"): mt940(),
             os.path.join(out["bank_cn"], "交易明细_demo.csv"): cn_bank_csv(),
             os.path.join(out["1c"], "EnterpriseData_demo.xml"): enterprise_data()}
    for path, data in files.items():
        with open(path, "wb") as fh:
            fh.write(data)
    single_window_list().to_excel(os.path.join(out["sw"], "报关数据查询_demo.xlsx"), index=False, sheet_name="报关单")
    print("Демо «Коннекторы/банк»:", ", ".join(os.path.relpath(p, ROOT) for p in list(files)
                                              + [os.path.join(out["sw"], "报关数据查询_demo.xlsx")]))


if __name__ == "__main__":
    main()
